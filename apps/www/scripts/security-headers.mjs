// Emit build/client/_headers — the security headers Cloudflare's Assets layer
// serves with the SPA. The Worker only sees /api/* (`run_worker_first`), so
// this file is the ONLY place the document's own headers can come from.
//
// It is generated rather than committed because of one line: `script-src`.
// The built index.html carries four INLINE scripts — the theme bootstrap from
// root.tsx, plus React Router's hydration-context and stream chunks — and a CSP
// worth having cannot say 'unsafe-inline' next to them. So each one is hashed
// here, at the only moment their exact bytes are known. A hand-written _headers
// would be stale on the next build, and a CSP that is stale is a CSP that gets
// deleted.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const clientDir = join(
  dirname(fileURLToPath(import.meta.url)),
  "../build/client",
);
const html = readFileSync(join(clientDir, "index.html"), "utf8");

// Inline only: a `src=` script is fetched from our own origin and covered by
// 'self'. The captured text must be byte-identical to what the browser hashes.
const hashes = [];
for (const [, attrs, body] of html.matchAll(
  /<script\b([^>]*)>([\s\S]*?)<\/script>/g,
)) {
  if (/\bsrc\s*=/.test(attrs)) continue;
  const digest = createHash("sha256").update(body, "utf8").digest("base64");
  hashes.push(`'sha256-${digest}'`);
}
if (hashes.length === 0) {
  throw new Error(
    "no inline scripts found in index.html — the CSP would be wrong; check the build output",
  );
}

const csp = [
  "default-src 'self'",
  // 'self' covers every chunk the module graph imports; the hashes cover the
  // inline bootstrap. Nothing else may run.
  `script-src 'self' ${hashes.join(" ")}`,
  // Base UI and Tailwind set element style attributes at runtime; there is no
  // hash for those. Style injection is not a script-execution primitive.
  "style-src 'self' 'unsafe-inline'",
  // GitHub avatars (people and orgs) are the only remote images.
  "img-src 'self' data: https://avatars.githubusercontent.com",
  "font-src 'self'",
  // The API is same-origin — one Worker serves both (wrangler.jsonc).
  "connect-src 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'none'",
  "upgrade-insecure-requests",
].join("; ");

// `/*` matches every asset path. The Worker sets its own headers on /api/*,
// which never reaches this layer.
const headers = `# GENERATED by scripts/security-headers.mjs — do not edit.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin
  Strict-Transport-Security: max-age=31536000; includeSubDomains
`;

writeFileSync(join(clientDir, "_headers"), headers);
console.log(
  `security-headers: wrote _headers (${hashes.length} script hashes)`,
);
